def build_distances():
    edges = []
    for f, t, name, cur, gate, note in E:
        def get(n):
            if n in CITIES:
                return CITIES[n]
            if n in ANCHORS:
                lon, lat, _ = ANCHORS[n]
                return {"lat": lat, "lon": lon}
            return None
        a, b = get(f), get(t)
        if not a or not b:
            print(f"[跳过] 缺坐标：{f}→{t}")
            continue
        nm = round(NM_OVERRIDE.get((f, t)) or nm_of(a, b))
        base = round(nm * ROUTE_FACTOR)
        cm = CURRENT_MOD.get(cur, 1.0)
        wa = WIND_ASSIST.get((f, t), 1.0)
        sf = STOP_OVERRIDE.get((f, t), stop_factor(nm))
        days = {k: round(base / (v * cm * wa) * sf) for k, v in SPEED.items()}
        edges.append({"from": NAME_FIX.get(f, f), "to": NAME_FIX.get(t, t), "route": name,
                      "nm": nm, "days": days, "current": cur, "knowledge_gate": gate, "note": note})
    doc = {
        "_meta": {
            "说明": "《燃帆》v1 五海区里程表（P3·T2.2.2）。基准天数=海里×1.15绕行系数÷船速档日均"
                    "（快120/中90/慢60），洋流顺×1.15/逆×0.85 已入格；季风与船况修正由分册08规则层叠加。",
            "knowledge_gate": "S1=古已有之；S2/S3/S4=纪门控（对表工程2 known-world 六纪元）；"
                              "PL 视图按知识态遮蔽（未知边不显示），GM 视图全开",
            "anchors": "特殊锚地（马德拉/佛得角/好望角等）为航路节点，不占 120 城名额",
            "audit": {"边数": len(edges)},
        },
        "edges": edges,
    }
    (HERE / "distances.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    return doc


