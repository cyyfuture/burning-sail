def g(name, cat, origin, age, base_gAg, unit_per, stow, keep, chain, tag="[确]", note=""):
    """unit_per: 每担换算系数（默认 gAg/kg×10.99）。特殊单位在 note 说明。"""
    picul = round(base_gAg * unit_per, 1) if isinstance(base_gAg, (int, float)) else None
    G.append({"name": name, "cat": cat, "origin": origin, "age": age,
              "base_gAg": base_gAg, "unit": "gAg/kg" if unit_per == PER_PICUL else "特殊",
              "picul_silver": picul, "stow": stow, "keep": keep,
              "chain": chain, "tag": tag, "note": note})

