def verify(d):
    """史实回放 8 例（±30%）＋季风 3 例。"""
    checks = [
        ("里斯本", "果阿", 150, "carreira 往航带（含停泊 120–180 天）"),
        ("威尼斯", "亚历山大港", 28, "4–6 周含停泊"),
        ("泉州", "马六甲", 25, "3–4 周"),
        ("热那亚", "布鲁日", 28, "3–4 周含海峡"),
        ("里斯本", "圣多明各", 30, "25–35 天信风快线"),
        ("好望角", "巴达维亚", 90, "VOC 外航印度洋段 2.5–3 月"),
        ("广州", "巴达维亚", 35, "中荷航线单段 4–6 周"),
        ("里斯本", "巴伊亚", 40, "南大西洋 30–50 天"),
    ]
    print("史实回放（中速档基准天 vs 史实带）：")
    ok = 0
    for f, t, hist, note in checks:
        e = [x for x in d["edges"] if x["from"] == f and x["to"] == t]
        if not e:
            e = [x for x in d["edges"] if x["from"] == t and x["to"] == f]
        if not e:
            print(f"  [缺边] {f}→{t}")
            continue
        days = e[0]["days"]["中"]
        dev = (days - hist) / hist * 100
        ok += abs(dev) <= 30
        print(f"  {f}→{t}: {days}天 vs {hist}天带（{note}）偏差 {dev:+.0f}% {'✓' if abs(dev) <= 30 else '✗'}")
    print(f"通过 {ok}/8")


