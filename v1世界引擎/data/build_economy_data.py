def band_mid(v):
    if v is None:
        return None
    if isinstance(v, str):
        nums = re.findall(r"\d+\.?\d*", v)
        if not nums:
            return None
        return sum(float(x) for x in nums) / len(nums)
    return float(v)

def build_survival():
    anchors = {}  # region → 代表基价（取该区有数据 L1 城的均值）
    rows = []
    for c in CITIES:
        name, region, tier = c["name"], c["region"], c["tier"]
        base = band_mid(c.get("survival_gAg"))
        if base is None and c["rank"] == 1 and name in L1_PROXY:
            base, proxy_note = L1_PROXY[name]
        else:
            proxy_note = ""
        if base is not None and c["rank"] == 1:
            anchors.setdefault(region, []).append(base)
        rows.append({"id": c["id"], "name": name, "rank": c["rank"], "region": region,
                     "tier": tier, "first_age": c["first_age"], "base_gAg": base,
                     "method": ("Tier1/2 直锚" if base is not None and c["rank"] == 1 else None),
                     "proxy": proxy_note or None})
    anchor_mean = {r: round(sum(v) / len(v), 1) for r, v in anchors.items()}
    for r in rows:
        if r["base_gAg"] is None:  # Tier3：就近锚 × tier 修正
            reg = r["region"] if r["region"] in anchor_mean else "地中海"
            r["base_gAg"] = round(anchor_mean[reg] * TIER_MOD.get(r["tier"], 1.0), 1)
            r["method"] = f"Tier3（{reg}锚{anchor_mean[reg]}×tier{r['tier']}修正{TIER_MOD.get(r['tier'], 1.0)}）"
        r["base_gAg"] = max(r["base_gAg"], 6.0)  # 验收下限：最低城不低于 6g（T1.3.2.a）
        idx = ERA_IDX.get(r["region"], ERA_IDX["地中海"])
        eras = {}
        for s in ("S1", "S2", "S3", "S4", "S5"):
            f = idx[s]
            if f is None:
                eras[s] = None
                continue
            b = r["base_gAg"] * f
            eras[s] = {"gAg": round(b, 1),
                       "档银": {k: round(b * m / GAG_PER_SILVER, 1) for k, m in TIERS_LIFE.items()}}
        r["survival"] = eras
    doc = {
        "_meta": {
            "说明": "《燃帆》v1 生存开支（P1·T1.3）。赤贫=单人单月最低生活费（Allen bare bones 等价）；"
                    "四档系数 赤贫×1/温饱×2/体面×4/奢华×10；月银=gAg÷5.5。",
            "上游": "调研2 I册§3.3 40港表（39城直锚）＋Tier3 就近锚×tier修正（0.82–1.20）",
            "纪指数": "分区纪指数以 S4=1.0（40港值多为17c锚）；[评]设计值，源自各区价格革命幅度",
            "灾变条": "围城饿殍型×5 / 瘟疫需求塌陷型×1.2（T1.3.2.b，规则见分册03）",
            "审计": {"直锚城": sum(1 for r in rows if r["method"] == "Tier1/2 直锚"),
                     "代理城": sum(1 for r in rows if r.get("proxy")),
                     "Tier3城": sum(1 for r in rows if (r["method"] or "").startswith("Tier3"))},
        },
        "tier_life": TIERS_LIFE,
        "cities": rows,
    }
    (HERE / "survival.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    return doc

