def city_tier_of(good, city):
    if good["name"] == "银锭":
        return "本位"  # 平价，不掷
    age_order = ["S1", "S2", "S3", "S4", "S5"]
    if city["first_age"] > good["age"]:  # 城还没开港
        return None
    # 纪门控：城所在纪早于品解锁纪 → 无货（GM 可放"奇物档"溢价4+）
    if age_order.index(good["age"]) > 0 and good["age"] > "S1" and city["first_age"] < good["age"]:
        pass  # 由 campaign 纪统一判断，城档仍给值
    orig = ORIGIN_REGION.get(good["name"])
    if orig is None:
        return "消费"
    if city["region"] == orig:
        return "产地"
    if city["name"] in TRANSSHIP.get(good["name"], []):
        return "中转"
    if OCEAN.get(city["region"]) != OCEAN.get(orig):
        return "遥远"
    # 中转判定：tier 高的跨区城作中转
    if city["tier"] <= 2:
        return "中转"
    return "消费"


TIER_MULT = {"产地": 0.6, "中转": 0.9, "消费": 1.6, "遥远": 2.2, "本位": 1.0}
TRACK_MULT = {0: 1.8, 1: 1.3, 2: 1.1, 3: 1.0, 4: 0.8, 5: 0.6}


def local_price(good, city):
    """本城交易基准：货源侧（产地/第一中转）按产地银，下游按到岸银；×城档。"""
    t = city_tier_of(good, city)
    if t is None:
        return None, None
    h = good.get("hold") or {}
    src = h.get("产地银") if (t == "产地" or city["name"] in SOURCE_SIDE.get(good["name"], [])) else None
    base = src if src else h.get("到岸银")
    if not base:
        return t, None
    return t, round(base * TIER_MULT[t])


def build_prices():
    grid = {}
    strips = {}
    for city in CITIES:
        rows = []
        for good in GOODS:
            t, p = local_price(good, city)
            if t is None or p is None:
                continue
            grid.setdefault(good["name"], {})[city["id"]] = {"tier": t, "base_silver": p}
            if city["rank"] == 1:
                rows.append((good["name"], t, p))
        # 市况条：一级城取有意义的品（产地+中转+高价消费品）
        if city["rank"] == 1:
            prio = {"产地": 0, "中转": 1, "消费": 2, "遥远": 3}
            rows.sort(key=lambda r: (prio[r[1]], -r[2]))
            strips[city["id"]] = {"name": city["name"], "region": city["region"],
                                  "goods": [{"品": n, "档": t, "基价银": p} for n, t, p in rows[:12]]}
    doc = {
        "_meta": {
            "说明": "《燃帆》v1 城市基价档位（P4·T3.1.1）。成交价=hold基价×城档×库存带×行情骰；"
                    "城档=产地0.6/中转0.9/消费1.6/遥远2.2；库存轨初始=3（常态）。",
            "库存带": {str(k): v for k, v in TRACK_MULT.items()},
            "轨移动": "玩家：卸N舱轨+N、购N舱轨−N（N≥3才推轨）；系统（季末）：产地+1至上限/消费−1至0/中转掷d6 4+±1；事件卡直拨",
            "市况侦察": "交易 DV13 探听：GM 如实报当前档（10章'探听行情'沿用）",
            "audit": {"品数": len(grid), "一级市况条": len(strips)},
        },
        "grid": grid,
        "strips": strips,
    }
    (HERE / "prices.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    return doc


def simulate_dump(doc):
    """砸盘模拟（T3.1.2.a 验收）：里斯本连抛三船胡椒（4舱×3）。"""
    cell = doc["grid"]["黑胡椒"]["lisbon"]
    base = cell["base_silver"]  # 本城基准（产地银或到岸银×城档）
    tier = cell["tier"]
    print(f"砸盘模拟（里斯本·胡椒；城档={tier}；本城基准 {base}）")
    track = 3
    for ship in range(1, 4):
        price = base * TRACK_MULT[track] * 1.0  # 行情=平常
        print(f"  第{ship}船（4舱）：库存轨={track} → 单舱成交 {price:.0f} 银（×{TRACK_MULT[track]}）")
        track = min(5, track + 1)
    final = base * TRACK_MULT[5]
    first = base * TRACK_MULT[3]
    print(f"  价差：首船 {first:.0f} → 第三船 {final:.0f}（{(final/first-1)*100:+.0f}%，验收目标 −40% 级）")


