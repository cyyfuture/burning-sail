def main():
    errs = []
    # 拆解卡自检
    if len(CORPUS) != 40:
        errs.append(f"拆解卡应 40 张，实 {len(CORPUS)}")
    works = [c["work"] for c in CORPUS]
    if len(set(works)) != 20:
        errs.append(f"语料种数应 20，实 {len(set(works))}")
    buckets = set()
    age_cover = {a: 0 for a in ("S1", "S2", "S3", "S4", "S5")}
    for c in CORPUS:
        if len(c["excerpt"]) > 400:
            errs.append(f"{c['id']} 摘录超 400 字")
        if c["quote_type"] not in ("公版原文", "技法仿写"):
            errs.append(f"{c['id']} 版权标注非法：{c['quote_type']}")
        cid = c["curtain"].split()[0]
        if cid not in CURTAIN_IDS:
            errs.append(f"{c['id']} 帷幕编号非法：{c['curtain']}")
        if len(c["techniques"]) < 3 or not c["demo"] or not c["usage"]:
            errs.append(f"{c['id']} 拆解三件套不全")
        buckets.add(c["bucket"])
        for a in c["ages"]:
            age_cover[a] += 1
    need_buckets = {"海与风暴", "港口与市井", "东亚航海", "人物与对话", "战争与权谋", "清单与账本"}
    if buckets != need_buckets:
        errs.append(f"主题桶缺口：{need_buckets - buckets}")
    for a, cnt in age_cover.items():
        if cnt < 3:
            errs.append(f"{a} 可用语料 <3 条（实 {cnt}）")
    # 句库自检
    if len(GLANCES) != 72:
        errs.append(f"句库应 72 条，实 {len(GLANCES)}")
    for q in (J, T, M):
        if sum(1 for g in GLANCES if g["腔"] == q) != 24:
            errs.append(f"{q} 不是 24 条")
    c_cov, g_cov = {}, {}
    for g_ in GLANCES:
        ref = g_["ref"]
        cov = g_cov if ref.startswith("G") else c_cov
        cov[ref] = cov.get(ref, 0) + 1
    for cid in CURTAIN_IDS:
        if c_cov.get(cid, 0) < 2:
            errs.append(f"帷幕 {cid} 句库覆盖 <2")
    for gi in range(1, GENERIC_COUNT + 1):
        if g_cov.get(f"G{gi:02d}", 0) < 2:
            errs.append(f"泛型 G{gi:02d} 句库覆盖 <2")
    if errs:
        print("自检未过：")
        for e in errs:
            print("  -", e)
        raise SystemExit(1)

